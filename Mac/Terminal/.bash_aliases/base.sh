alias ll='ls -lahF'                    # Human-readable long listing with file type indicators.
alias ..='cd ..'                       # Jump up one directory quickly.
alias ...='cd ../..'                   # Jump up two directories with a single command.
alias grep='grep --color=auto'         # Highlight matching text for easier reading.
alias mkdir='mkdir -pv'                # Create parent directories and show what was created.
alias c="clear"                        # Clear the terminal screen with a single letter.
alias h='history'                      # Show command history.
alias j='jobs -l'                      # List background jobs.